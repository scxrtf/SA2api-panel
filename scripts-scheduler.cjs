"export function startScheduler(): void {",
"  if (state.running) return;",
"  state.running = true;",
"  console.log(\"[scheduler] 进程内调度器已启动（Asia/Shanghai 时点）\");",
"  void mainLoop();",
"  restartBalanceLoop();",
"}",
